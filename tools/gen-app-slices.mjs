#!/usr/bin/env node
/**
 * THE SLICES OF TWO JSON FILES THE APP READS, GENERATED SO THE REST OF EACH STAYS OFF THE PHONE.
 *
 *   node tools/gen-app-slices.mjs                            # write both slices
 *   node tools/gen-app-slices.mjs --check                    # exit 1 if either is stale (CI)
 *   node tools/gen-app-slices.mjs --only packages/brand      # just the slices under a path
 *
 * Copied from CuddleCue's tool on 2026-10-08, when NibbleCue's repository was seeded from it.
 * `--only <path prefix>` is NibbleCue's addition: it writes (or checks) only the slices whose
 * target starts with the prefix, so a change to one package's source regenerates that package's
 * slice and leaves the other package's file alone.
 *
 * WHY. Metro bundles an imported JSON file whole; it cannot take one key of it. The app imported
 * two files for a slice each (CuddleCue, 2026-09-26; NibbleCue keeps the same two):
 *
 *   packages/core/src/plan/pricing.config.json. The app reads `packages` (`packages.ts`) and
 *     `welcome_preview.days` (`welcome.ts`). The rest is the store dashboards' notes.
 *   packages/brand/store-listing.json. The app reads `inApp` (`IN_APP_STRINGS`). The rest is
 *     the App Store, Play, website and email drafts.
 *
 * So each slice is copied VERBATIM into a small module the code imports instead. The JSON files
 * stay the one source, are only ever read here, and keep every test that reads them; nothing is
 * derived or rewritten on the way — the product ids in `packages` are the config's, character
 * for character (CLAUDE.md §2: a subscription product id is never rewritten by a script).
 *
 * A copy can go stale, so each is held to its source twice: `--check`, and a test in its own
 * package (`plan/pricing.generated.test.ts` under `pnpm test:entitlements`, `src/index.test.ts`
 * under `pnpm test:brand`).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const onlyAt = process.argv.indexOf('--only');
const only = onlyAt === -1 ? null : process.argv[onlyAt + 1];
if (onlyAt !== -1 && !only) throw new Error('--only needs a path prefix, like packages/brand');
const RUN = 'node tools/gen-app-slices.mjs';

const readJson = rel => JSON.parse(readFileSync(join(root, rel), 'utf8'));
const literal = value => JSON.stringify(value, null, 2);

const PRICING = 'packages/core/src/plan/pricing.config.json';
const LISTING = 'packages/brand/store-listing.json';
const pricing = readJson(PRICING);
const listing = readJson(LISTING);

if (!Array.isArray(pricing.packages) || typeof pricing.welcome_preview?.days !== 'number') {
  throw new Error(`${PRICING}: expected \`packages\` and \`welcome_preview.days\``);
}
if (listing.inApp === null || typeof listing.inApp !== 'object') {
  throw new Error(`${LISTING}: expected an \`inApp\` object`);
}

const header = (source, what) => `/**
 * GENERATED by tools/gen-app-slices.mjs from ${source} — do not edit.
 * Change the source, then run \`${RUN}\`.
 *
 * ${what}
 */`;

const SLICES = [
  {
    target: 'packages/core/src/plan/pricing.generated.ts',
    text: `${header(
      'pricing.config.json',
      "The two parts of the config the app reads — the packages (`packages.ts`) and the length of\n * the welcome preview (`welcome.ts`) — so the rest of it, the store dashboards' mirror of the\n * plan matrix, is not bundled. Prices here are TARGETS for the store dashboards; a price a parent\n * sees comes from the store at runtime (CLAUDE.md rule 13).",
    )}
/** \`packages\`, whole and in the config's order. */
export const PRICING_PACKAGES = ${literal(pricing.packages)};

/** \`welcome_preview.days\`. */
export const WELCOME_PREVIEW_DAYS = ${literal(pricing.welcome_preview.days)};
`,
  },
  {
    target: 'packages/brand/src/inApp.generated.ts',
    text: `${header(
      '../store-listing.json',
      '`inApp`, the only part of the store listing the app renders (`IN_APP_STRINGS`), so the App\n * Store, Play, website and email drafts are not bundled.',
    )}
export const IN_APP = ${literal(listing.inApp)};
`,
  },
];

const prettierrc = JSON.parse(readFileSync(join(root, '.prettierrc'), 'utf8'));
const stale = [];
const chosen = only === null ? SLICES : SLICES.filter(s => s.target.startsWith(only));
if (chosen.length === 0) throw new Error(`--only ${only}: no slice has a target under that path`);
for (const { target, text } of chosen) {
  const out = await format(text, { ...prettierrc, parser: 'typescript' });
  const abs = join(root, target);
  if (existsSync(abs) && readFileSync(abs, 'utf8').replace(/\r\n/g, '\n') === out) continue;
  stale.push(relative(root, abs));
  if (!check) writeFileSync(abs, out);
}

if (check && stale.length > 0) {
  console.error(`[slices] stale:\n  ${stale.join('\n  ')}\n— run ${RUN}`);
  process.exit(1);
}
console.log(
  stale.length === 0
    ? '[slices] the app’s JSON slices are up to date'
    : `[slices] wrote ${stale.join(', ')}`,
);
